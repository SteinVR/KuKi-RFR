"""E2 report and oracle/error summaries from saved candidate audit, no models."""

import json
import re
from pathlib import Path

import numpy as np

from research.kuki.data import FAMILIES, write_json
from research.kuki.experiment import load_development

ROOT = Path(__file__).parent
OUT = ROOT / "E2-proposals"


def main():
    data = json.loads((OUT / "metrics.json").read_text())
    docs, _ = load_development(json.loads(Path("research/configs/data.json").read_text()))
    names = {
        "sentences": "Предложения",
        "clauses_sentences": "Пунктуационные части + предложения",
        "ngrams8": "1–8 токенов",
        "ngrams32": "1–32 токена",
        "multiscale": "Многомасштабный набор",
        "all_word_spans_analytic": "Все последовательности токенов (аналитически)",
    }
    extra = {}
    for method in names:
        extra[method] = {}
        for split in docs:
            records = json.loads((OUT / f"{method}-{split}.json").read_text())
            bounds = []
            support = dict.fromkeys(FAMILIES, 0)
            missed = dict.fromkeys(FAMILIES, 0)
            lengths = []
            aligned = 0
            for d, r in zip(docs[split], records, strict=True):
                values = []
                for ai, a in enumerate(d["annotations"]):
                    g = a["l3_persuasion"]
                    for s in g:
                        support[s["label"]] += 1
                    if g:
                        hits = len(g) - sum(m["annotation_index"] == ai for m in r["misses"])
                        values.append(2 * hits / (len(g) + hits))
                if values:
                    bounds.append(float(np.mean(values)))
                for m in r["misses"]:
                    missed[m["label"]] += 1
                    lengths.append(m["length"])
                    aligned += int(m["word_aligned"])
            extra[method][split] = dict(
                oracle_individual_exact_f1=float(np.mean(bounds)),
                raw_family_support=support,
                raw_misses=missed,
                raw_miss_count=len(lengths),
                raw_misses_token_aligned=aligned,
                miss_character_length_quantiles=np.quantile(lengths, [0, 0.5, 0.9, 1]).tolist()
                if lengths
                else [],
            )
    write_json(OUT / "analysis.json", extra)
    lines = [
        "# E2. Необучаемые генераторы фрагментов L3\n",
        """Эксперимент завершён на train/dev. Полный перебор последовательностей токенов не выбран основным генератором: медиана749700 кандидатов на dev-статью при точном охвате93.15%. Этот эксперимент измеряет ограничения пространства кандидатов, а не качество распознавания риторики.\n
## Исследовательский вопрос и данные\n
Сколько эталонных фрагментов доступно последующему идеальному классификатору и какова цена такого охвата? Гипотеза: простая структура текста уменьшает число кандидатов, но теряет точные авторские границы; расширение n-грамм повышает охват ценой большого числа нерелевантных пар.\n
Использован закреплённый русский split145 train /31 dev /31 test. Test не участвовал. Разметчики оцениваются отдельно: показатели сначала усредняются внутри ответа, затем между непустыми ответами статьи, затем между статьями. Из охвата исключены16 полностью пустых train-статей и2 dev-статьи; в стоимости генерации учтены все статьи. Множественные семейства на одной паре учитываются как отдельные размеченные элементы. Это согласовано с задачей последующей типизированной классификации; E3 дополнительно считает уникальные нетипизированные пары.\n
## Методы и настройки\n
Генераторы используют только текст. Razdel0.5.0 даёт предложения и токены с исходными символьными смещениями. Важно: здесь токены включают пунктуацию, поэтому старое техническое имя `words`/`all_word_spans` в JSON не означает исключительно лексические слова.\n
* Предложения — все пары их исходных границ.\n* Пунктуационные части — разделение по запятой, точке с запятой, двоеточию, вопросительному/восклицательному знаку, тире и переносу; добавляются целые предложения. Это эвристика, не синтаксический анализ.\n* N-граммы — все непрерывные последовательности1–8 либо1–32 токенов, без обучения и отбора по эталону.\n* Многомасштабный набор — части, объединения до3 соседних частей, предложения, пары соседних предложений, непустые строки и n-граммы1–8; дубликаты пар удаляются.\n* Полный перебор — N(N+1)/2 последовательностей. Квадратичный список не материализуется: точное присутствие пары проверяется по допустимым началам/концам; лучший IoU — по ближайшим допустимым границам. Отдельный тест сравнивает аналитический результат с полным перебором на всех символьных фрагментах короткого текста.\n
Никакие фрагменты разметки не заменяются предложениями или токенами. Границы эталона не нормализуются. Параметры фиксированы до измерений. Обучения и поиска гиперпараметров нет.\n
## Результаты\n
Точный охват — доля эталонных фрагментов, для которых существует кандидат с обеими точными границами. IoU≥0.5 — существование кандидата, перекрывающего не менее половины объединения двух интервалов; один кандидат здесь может покрывать несколько эталонов. Это **не** one-to-one F1.\n""",
    ]
    for split in ["train", "dev"]:
        lines += [
            f"### {split}\n",
            "| Генератор | Точный охват | IoU≥0.5 | Медиана кандидатов | P90 | Генерация на весь split, с |\n|---|---:|---:|---:|---:|---:|",
        ]
        for method, name in names.items():
            m = data["results"][method][split]
            q = m["candidate_count_quantiles"]
            lines.append(
                f"| {name} | {m['exact_recall']:.4f} | {m['iou50_coverage']:.4f} | {q[1]:.0f} | {q[2]:.0f} | {m['generation_seconds']:.3f} |"
            )
        lines.append("")
    lines += [
        "Для аналитического полного набора в колонке времени измерена только токенизация/подсчёт, **не** материализация и **не** нейронная оценка миллионов кандидатов. Для остальных методов это построение списка, без классификатора. Все измерения CPU, один проход; параллельно работал E1, поэтому это ориентир стоимости, не строгий сравнительный бенчмарк.\n",
        "### Идеальный последующий классификатор\n",
        "| Генератор | Верхняя граница exact-F1 на dev |\n|---|---:|",
    ]
    for method, name in names.items():
        lines.append(f"| {name} | {extra[method]['dev']['oracle_individual_exact_f1']:.4f} |")
    lines += [
        "\nЭта граница предполагает знание каждого индивидуального ответа: выдаются все и только доступные точные эталоны, ложных срабатываний нет. Для ответа с R охватом F1=2R/(1+R); усреднение выполнено **после** расчёта по ответам. Единственный общий прогноз не обязан одновременно достигать этих границ при несогласии разметчиков. Лимит100 выходов здесь не применяется. Это недостижимый в общем случае диагностический потолок, не результат модели.\n",
        "## Ошибки и ограничения\n",
        "| Семейство | Эталонов dev, сырое число | Пропущено многомасштабным | Пропущено полным токенным набором |\n|---|---:|---:|---:|",
    ]
    for f in FAMILIES:
        m = extra["multiscale"]["dev"]
        a = extra["all_word_spans_analytic"]["dev"]
        lines.append(
            f"| {f} | {m['raw_family_support'][f]} | {m['raw_misses'][f]} | {a['raw_misses'][f]} |"
        )
    m = extra["multiscale"]["dev"]
    a = extra["all_word_spans_analytic"]["dev"]
    lines += [
        f"\nУ многомасштабного набора{m['raw_miss_count']} сырых пропусков, из них{m['raw_misses_token_aligned']} имеют допустимые токенные границы: они теряются из-за ограниченной длины/набора структур. Медиана длины пропуска{m['miss_character_length_quantiles'][1]:.0f} символов. У полного набора{a['raw_miss_count']} пропусков, все связаны с несовпадением хотя бы одной точной токенной границы. Это описание данных, а не автоматическое признание разметки ошибочной. Сырые количества не являются независимыми наблюдениями.\n",
        """При IoU≥0.5 многомасштабный набор достигает полного охвата на dev, но его точный охват71.46% и тысячи кандидатов сохраняют две отдельные проблемы: локализацию и фильтрацию. Результат не доказывает, что дробление по пунктуации решает L3.\n
Параметры не подбирались на test; статистическая неопределённость между статьями и чувствительность к другому корпусу не оценивались. Все выводы относятся к текущему train/dev.\n
## Вывод и следующее использование\n
N-граммы полезны как контролируемый диагностический baseline и как часть ограниченного набора кандидатов. Полный перебор для передачи всех пар дорогому классификатору не оправдан этими результатами. Для основной архитектуры проверяется независимый обучаемый генератор E3; его небольшой top-K нужно сравнивать по тому же охвату и отдельно оценивать всю цепочку. Возможная гибридизация E3 с эвристиками — последующий эксперимент, здесь не выполнена.\n
## Стоимость, артефакты и воспроизведение\n""",
        f"Один сохранённый CPU-аудит занял{data['elapsed_seconds']:.2f}с, GPU-обновлений0. Был один предыдущий такой же запуск до технической правки `zip(strict=False)`; содержательные настройки и выводы не менялись. Полное время двух CPU-проходов не объединялось в GPU-бюджет.\n",
        """Из корня репозитория:\n
```bash
uv run --locked python -m research.stages.ST2-l3-rhetoric.modular.proposal_audit
uv run --locked python -m research.stages.ST2-l3-rhetoric.modular.report_proposals
```

[Метрики](metrics.json), [разбор ошибок и oracle](analysis.json), индивидуальные статьи — `<method>-<split>.json`; код и SHA256 генератора указаны в метриках. [Протокол](../protocol.md). Источники: [Razdel](https://github.com/natasha/razdel), [закреплённая версия](https://pypi.org/project/razdel/0.5.0/).\n
## Self-review\n
Проверены неизменность split/source, отсутствие test в расчётах, отдельное усреднение ответов и статей, аналитическая формула на явном переборе, различие oracle-покрытия и реального F1, пунктуационные токены, невозможность трактовать аналитическое время как цену полного перебора. Отчёт не приписывает генераторам качество классификации.\n""",
    ]
    (OUT / "report.md").write_text(
        re.sub(r"(?<=[А-Яа-яЁё])(?=\d)|(?<=\d)(?=[А-Яа-яЁё])", " ", "\n".join(lines))
    )


if __name__ == "__main__":
    main()
